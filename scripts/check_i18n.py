#!/usr/bin/env python3
"""Consistency checks for the i18n translation tables and the
error-code registry of the OpenAPI contract.

The repository's translation conventions (see i18n/README.md):

  1. Every translation file is a flat JSON object: no nesting, every
     value is a string, and no key appears twice.
  2. Keys are lowercase snake_case identifiers matching ^[a-z0-9_]+$.
     Error-code keys are the error code lowercased
     (SETUP_ALREADY_COMPLETED -> setup_already_completed).
  3. en.json is the source of truth. Every other language file must
     carry exactly the same key set: missing and unexpected keys are
     both violations. (When more community-maintained languages land,
     this can soften to a coverage threshold; for now en and zh-Hans
     are both fully maintained, so exact equality is required.)
  4. ICU message placeholders ({name}) in a translation must match the
     placeholder set of the English string for the same key. Only
     simple {name} placeholders are compared.
  5. The error-code registry of the contract, the enum under
     components.schemas.Error.properties.code in openapi/lumemor.yaml,
     and en.json must agree in both directions: every enum code has a
     translation key (its lowercase form), and every en.json key that
     is not allowlisted in NON_ERROR_KEYS is the lowercase form of an
     enum code, so orphaned error-code keys cannot survive.

Every violation is printed with the file it belongs to and makes the
script exit with status 1. With no violations a one-line summary is
printed and the script exits 0.

Usage: python3 scripts/check_i18n.py [REPO_ROOT]

REPO_ROOT is the directory holding i18n/ and openapi/; it defaults to
the repository this script lives in. The argument exists for the
negative-fixture tests (scripts/test_check_i18n.sh), which copy the
real files into a temporary directory, break exactly one of them, and
expect a non-zero exit. Two mutually exclusive flags select a subset
of the checks; the i18n workflow runs them as separate steps so a red
build is easy to attribute in the CI log:

  --translations-only   run checks 1-4 only
  --error-codes-only    run check 5 only

The script is pure standard-library Python 3 and expects to live in
scripts/ next to the i18n/ directory of the repository. The yaml is
parsed with line-level indentation tracking, not a yaml library; if
the generated shape of the contract ever moves so that the enum can no
longer be located, that is reported as a violation and the script
fails. It never passes silently without the error-code registry.
"""

