KEY_PATTERN = re.compile(r"^[a-z0-9_]+$")
PLACEHOLDER_PATTERN = re.compile(r"\{([A-Za-z0-9_]+)\}")
# A "key: value" line of the contract. The key may be a plain
# identifier, a $ref, or an URL path such as /auth/login; the value is
# everything after the first colon and is empty for nested mappings.
KEY_LINE_PATTERN = re.compile(r"^(?P<key>[^\s#][^:]*):(?P<value>.*)$")


def load_file(path: Path, violations: list) -> dict:
    """Parse one translation file, checking structure and key naming.

    Returns the key-to-string mapping. Files that cannot be parsed or
    that are not flat objects yield an empty mapping; every problem is
    appended to violations.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as err:
        violations.append(f"{path.name}: cannot read file ({err})")
        return {}

    def reject_duplicates(pairs):
        seen = set()
        for key, _ in pairs:
            if key in seen:
                violations.append(f"{path.name}: duplicate key {key!r}")
            seen.add(key)
        return dict(pairs)

    try:
        data = json.loads(text, object_pairs_hook=reject_duplicates)
    except json.JSONDecodeError as err:
        violations.append(f"{path.name}: invalid JSON ({err})")
        return {}

    if not isinstance(data, dict):
        violations.append(f"{path.name}: top level must be a JSON object")
        return {}

    strings = {}
    for key, value in data.items():
        if not KEY_PATTERN.match(key):
            violations.append(
                f"{path.name}: key {key!r} must be lowercase snake_case "
                f"({KEY_PATTERN.pattern})"
            )
        if isinstance(value, str):
            strings[key] = value
        else:
            violations.append(
                f"{path.name}: value for {key!r} must be a string "
                "(translations must stay flat, no nesting)"
            )
    return strings


def check_against_source(name: str, table: dict, source: dict, violations: list) -> None:
    """Compare one language file with the source language file."""
    for key in sorted(set(table) - set(source)):
        violations.append(
            f"{name}: key {key!r} does not exist in {SOURCE_FILE}"
        )
    for key in sorted(set(source) - set(table)):
        violations.append(
            f"{name}: key {key!r} is missing ({SOURCE_FILE} is the source of truth)"
        )
    for key in sorted(set(table) & set(source)):
        expected = sorted(PLACEHOLDER_PATTERN.findall(source[key]))
        actual = sorted(PLACEHOLDER_PATTERN.findall(table[key]))
        if actual != expected:
            violations.append(
                f"{name}: placeholders for key {key!r} do not match "
                f"{SOURCE_FILE} (expected {expected}, got {actual})"
            )


def strip_quotes(value: str) -> str:
    """Remove a matching pair of single or double quotes."""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


def extract_error_codes(yaml_path: Path, violations: list):
    """Collect the Error.code enum values from the OpenAPI contract.

    The yaml is walked line by line, tracking the stack of open mapping
    keys by indentation, until the nesting path of ERROR_ENUM_PATH is
    reached; the list items under that key are the error codes. Returns
    the codes, or None when the contract could not be parsed (missing
    file, unparseable line, missing enum, empty enum); every such
    failure is appended to violations so a broken parse can never be
    mistaken for a passing check.
    """
    try:
        lines = yaml_path.read_text(encoding="utf-8").splitlines()
    except OSError as err:
        violations.append(f"{yaml_path}: cannot read the OpenAPI contract ({err})")
        return None

    codes = []
    stack = []  # open mapping keys as (indent, key) pairs
    enum_indent = -1
    in_enum = False
    enum_seen = False
    # A key line that carries an inline value (a plain scalar such as
    # "summary: ...", a quoted scalar, or a | / > block scalar) is only
    # ever followed by more-indented continuation text, never by
    # structure: deeper lines are skipped until the indentation drops
    # back to (or below) the key's own level.
    literal_indent = -1

    for lineno, raw in enumerate(lines, 1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip(" "))

        if literal_indent >= 0:
            if indent > literal_indent:
                continue  # continuation text of a multi-line scalar value
            literal_indent = -1

        if stripped.startswith("- "):
            if in_enum and indent > enum_indent:
                codes.append(strip_quotes(stripped[2:].strip()))
            continue

        match = KEY_LINE_PATTERN.match(stripped)
        if match is None:
            violations.append(
                f"{yaml_path}:{lineno}: cannot parse line {stripped!r}; "
                "the generated shape of the contract moved, update the "
                "line-level parsing in scripts/check_i18n.py"
            )
            return None

        while stack and indent <= stack[-1][0]:
            stack.pop()
        stack.append((indent, match.group("key")))
        in_enum = tuple(key for _, key in stack) == ERROR_ENUM_PATH
        if in_enum:
            enum_seen = True
            enum_indent = indent

        if match.group("value").strip():
            literal_indent = indent

    if not enum_seen:
        violations.append(
            f"{yaml_path}: {'.'.join(ERROR_ENUM_PATH)} not found; the "
            "generated shape of the contract moved, update the line-level "
            "parsing in scripts/check_i18n.py"
        )
        return None
    if not codes:
        violations.append(
            f"{yaml_path}: {'.'.join(ERROR_ENUM_PATH)} is empty; refusing "
            "to pass without the error-code registry"
        )
        return None
    return codes


def cross_check_error_codes(codes: list, source: dict, violations: list) -> None:
    """Check 5: the Error.code enum and en.json must agree both ways."""
    translated = {code.lower() for code in codes}
    for code in codes:
        key = code.lower()
        if key not in source:
            violations.append(
                f"{SOURCE_FILE}: error code {code} ({OPENAPI_YAML}) has no "
                f"translation key {key!r}; add the lowercase form of the code"
            )
    for key in sorted(source):
        if key in NON_ERROR_KEYS:
            continue
        if key not in translated:
            violations.append(
                f"{SOURCE_FILE}: key {key!r} is not the lowercase form of "
                f"any error code in {OPENAPI_YAML}; if the code was removed, "
                "remove the key as well; if this is a UI string, allowlist "
                "it in NON_ERROR_KEYS in scripts/check_i18n.py"
            )


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Check the i18n translation tables and cross-check them "
            "against the Error.code enum of the OpenAPI contract."
        )
    )
    checks = parser.add_mutually_exclusive_group()
    checks.add_argument(
        "--translations-only",
        action="store_true",
        help="run only the translation-file checks (1-4)",
    )
    checks.add_argument(
        "--error-codes-only",
        action="store_true",
        help="run only the error-code cross-check (5)",
    )
    parser.add_argument(
        "repo_root",
        nargs="?",
        type=Path,
        default=None,
        help="directory holding i18n/ and openapi/ "
        "(default: the repository of this script)",
    )
    args = parser.parse_args()

    repo_root = args.repo_root.resolve() if args.repo_root else DEFAULT_REPO_ROOT
    i18n_dir = repo_root / "i18n"
    openapi_yaml = repo_root / OPENAPI_YAML

    violations: list = []
    tables: dict = {}
    source: dict = {}

    if not args.error_codes_only:
        if not i18n_dir.is_dir():
            print(f"error: i18n directory not found: {i18n_dir}", file=sys.stderr)
            return 1

        files = sorted(i18n_dir.glob("*.json"))
        if not files:
            print(f"error: no translation files found in {i18n_dir}", file=sys.stderr)
            return 1

        tables = {path.name: load_file(path, violations) for path in files}

        source = tables.get(SOURCE_FILE)
        if source is None:
            violations.append(f"{SOURCE_FILE}: missing, but it is the source language file")
            source = {}

        for name, table in tables.items():
            if name != SOURCE_FILE:
                check_against_source(name, table, source, violations)
    else:
        # The cross-check still needs the source of truth.
        source = load_file(i18n_dir / SOURCE_FILE, violations)

    if not args.translations_only:
        codes = extract_error_codes(openapi_yaml, violations)
        if codes is not None:
            cross_check_error_codes(codes, source, violations)

    if violations:
        print(f"i18n check FAILED: {len(violations)} violation(s):")
        for violation in violations:
            print(f"  - {violation}")
        return 1

    parts = []
    if not args.error_codes_only:
        languages = ", ".join(name.removesuffix(".json") for name in tables)
        parts.append(f"{len(tables)} file(s) [{languages}], {len(source)} key(s)")
    if not args.translations_only:
        parts.append(f"{len(codes)} error code(s)")
    print(f"i18n check OK: {', '.join(parts)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
